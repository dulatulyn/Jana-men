import type { Locale, Profile, UserRole } from "./types.js";

const BOUNDARY = "(?:(?<![\\p{L}\\p{N}])(?=[\\p{L}\\p{N}])|(?<=[\\p{L}\\p{N}])(?![\\p{L}\\p{N}]))";
function U(re: RegExp): RegExp {
  return new RegExp(re.source.split("\\b").join(BOUNDARY), re.flags.includes("u") ? re.flags : re.flags + "u");
}

export type RefusalReason = "injection" | "other_person" | "hr_decision";

export interface GuardResult {
  reason: RefusalReason;
  pattern: string;
}

