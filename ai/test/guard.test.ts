describe("small talk and HR handoff text", () => {
  it.each([
    ["привет", "greeting"],
    ["Привет!", "greeting"],
    ["Здравствуйте.", "greeting"],
    ["Добрый день!", "greeting"],
    ["Сәлеметсіз бе?", "greeting"],
    ["спасибо", "thanks"],
    ["Спасибо большое!", "thanks"],
    ["ок, спасибо", "thanks"],
    ["Рақмет!", "thanks"],
  ])("%s is small talk (%s)", (q, kind) => expect(detectSmallTalk(q)).toBe(kind));

  it.each(["Привет! Сколько дней отпуска мне положено?", "спасибо, а когда аванс?", "привет 123", "хорошо, значит заявка уже одобрена?", "Сколько дней отпуска?"])(
    "%s is not small talk",
    (q) => expect(detectSmallTalk(q)).toBeNull(),
  );

  it("drops only the sentences that offer «Передать в HR»", () => {
    const text =
      "Политика компании: напишите HR-менеджеру на hr@jana.demo или нажмите «Передать в HR» в чате ассистента и укажите, какая справка нужна и для чего. Справка готовится в течение 2 рабочих дней, электронная версия приходит на почту.";
    expect(withoutHrHandoff(text)).toBe("Справка готовится в течение 2 рабочих дней, электронная версия приходит на почту.");
    expect(withoutHrHandoff("- Нажмите «Передать в HR».\n- Справка готовится 2 рабочих дня.")).toBe("- Справка готовится 2 рабочих дня.");
    expect(withoutHrHandoff("Ассистент чатында «HR-ге жіберу» батырмасын басыңыз.")).toBe("");
  });
});
